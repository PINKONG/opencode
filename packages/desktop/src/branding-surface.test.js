import { describe, expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const dir = dirname(fileURLToPath(import.meta.url))
const read = (path) => readFileSync(join(dir, path), "utf8")

describe("desktop branding surface", () => {
  test("does not expose old brand in visible desktop metadata and links", () => {
    const menu = read("./main/menu.ts")
    const index = read("./renderer/index.tsx")
    const appstream = read("../resources/ai.wiscode.desktop.metainfo.xml")
    const latest = read("../scripts/finalize-latest-json.ts")
    const workflow = read("../../../.github/workflows/publish.yml")
    const electronCfg = read("../electron-builder.config.ts")
    const downloadRoute = read("../../../packages/console/app/src/routes/download/[channel]/[platform].ts")
    const publish = read("../../../packages/opencode/script/publish.ts")

    expect(menu).not.toContain("https://opencode.ai/docs")
    expect(menu).not.toContain("https://discord.com/invite/opencode")
    expect(menu).not.toContain("https://github.com/anomalyco/opencode/issues/new?template=feature_request.yml")
    expect(menu).not.toContain("https://github.com/anomalyco/opencode/issues/new?template=bug_report.yml")
    expect(index).not.toContain("https://opencode.ai/favicon-96x96-v3.png")
    expect(index).toContain('const deepLinkEvent = "wiscode:deep-link"')
    expect(index).not.toContain('const deepLinkEvent = "opencode:deep-link"')
    expect(appstream).not.toContain("OpenCode is an open source agent")
    expect(appstream).not.toContain("https://opencode.ai")
    expect(appstream).not.toContain("https://github.com/anomalyco/opencode")
    expect(latest).toContain('asset: "wiscode-desktop-windows-x64.exe"')
    expect(latest).not.toContain("opencode-desktop-windows-x64.exe")
    expect(workflow).toContain("if: github.repository == 'PINKONG/opencode'")
    expect(workflow).toContain('OUT_NAME="wiscode-desktop-darwin-x64.app.tar.gz"')
    expect(workflow).toContain('OUT_NAME="wiscode-desktop-darwin-aarch64.app.tar.gz"')
    expect(workflow).not.toContain("github.repository == 'anomalyco/opencode'")
    expect(workflow).not.toContain('OUT_NAME="opencode-desktop-mac-x64.app.tar.gz"')
    expect(workflow).not.toContain('OUT_NAME="opencode-desktop-mac-arm64.app.tar.gz"')
    expect(downloadRoute).toContain("https://api.github.com/repos/PINKONG/opencode/releases")
    expect(downloadRoute).toContain("asset.browser_download_url")
    expect(downloadRoute).toContain('"windows-x64-nsis": "WisCode Installer.exe"')
    expect(downloadRoute).toContain('"darwin-aarch64-dmg": "WisCode.dmg"')
    expect(downloadRoute).not.toContain("OpenCode Desktop")
    expect(downloadRoute).not.toContain("anomalyco/opencode")
    expect(publish).toContain('const image = "ghcr.io/PINKONG/opencode"')
    expect(publish).toContain("https://github.com/PINKONG/opencode/releases/download/")
    expect(publish).not.toContain("ghcr.io/anomalyco/opencode")
    expect(publish).not.toContain("https://github.com/anomalyco/opencode/releases/download/")
    expect(electronCfg).toContain('prod: "ai.wiscode.desktop"')
    expect(electronCfg).not.toContain('appId: "ai.opencode.desktop"')
  })
})
